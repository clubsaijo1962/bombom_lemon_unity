        /// シードとプレイヤーインデックスから、このプレイヤーのお題を返す。
        /// 同じ引数なら必ず同じ結果（全クライアントで再現可能）。
        /// </summary>
        public static string GetTopic(int seed, int playerIndex)
        {
            var rng = new System.Random(seed * 31 + playerIndex * 17);
            return Topics[rng.Next(0, Topics.Length)];
        }

        /// <summary>
        /// シードとプレイヤーインデックスから、このプレイヤーの秘密の数字（1〜99）を返す。
