        /// </summary>
        public static int GetSecretNumber(int seed, int playerIndex)
        {
            // お題と独立したシードを使い、異なる数字になるようにする
            var rng = new System.Random(seed * 37 + playerIndex * 13 + 5);
            return rng.Next(1, 100); // 1〜99
